// the next season by themselves. The month a sentence names, and the
// temperatures beside it (data/months.ts), are read from the computed date;
// every sentence that depends on the two Easters being apart has a variant for
// the years they share a day (EASTER.same, 2028 and 2031).
//
// WHAT EACH EDITION ADDS. Russian: the Coptic Easter is always the Russian
// Orthodox Easter — the reader's own feast, kept on the same night; how near
// it falls to the May holidays, worked out from EASTER.orthodox; Egypt as most
// Russians know it, the Red Sea, combined with Cairo and Luxor; St Catherine's
// in Sinai, Greek Orthodox, whose hours on feast days we confirm. Arabic, in
// MSA and the plural: written for Arab Christians of the Levant, Iraq and the
// Gulf, whichever calendar their church keeps, and for every Arab family that
// knows Sham El-Nessim as a day out.
//
// The guide is never gendered: Russian "египтолог" only as the profession,
// with no pronoun; Arabic "إرشاد … متخصص في علم المصريات", as on the eclipse
