const MONTH_SLUGS = [
  "january", "february", "march", "april", "may", "june",
  "july", "august", "september", "october", "november", "december",
];
/** 0-based month of an ISO day. */
const monthIndex = (iso: string) => Number(iso.slice(5, 7)) - 1;
/** The month guide (temperatures) for the month an ISO day falls in. */
const monthOf = (iso: string) => findMonth(MONTH_SLUGS[monthIndex(iso)])!;

const { western: W, orthodox: O, palm: P, sham: S, same: SAME } = EASTER;
const Y = EASTER_Y;
/** Weeks between the two Easters: 0, 1, 4 or 5. */
const GAP_WEEKS = Math.round(EASTER.gap / 7);
const T_W = monthOf(W).temps;
const T_O = monthOf(O).temps;
/** Coptic Easter in April (it is never earlier); otherwise May, and hotter. */
const O_IN_APRIL = monthIndex(O) === 3;
/** The two Easters fall in different months (e.g. late March and early May). */
const SPLIT_MONTHS = !SAME && monthIndex(W) !== monthIndex(O);
const mar = findMonth("march")!.temps;
const apr = findMonth("april")!.temps;
const may = findMonth("may")!.temps;

